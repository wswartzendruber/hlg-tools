use std::{
    fs::File,
    io::{stdout, BufWriter, Write},
};
use dsp::{
    tf::{sdr_e_to_o, sdr_o_to_e},
    pixel::{OklchPixel, RgbPixel},
};
use clap::{app_from_crate, crate_authors, crate_description, crate_name, crate_version, Arg};
use rayon::prelude::*;

fn main() {

    let matches = app_from_crate!()
        .arg(Arg::with_name("title")
            .long("title")
            .short("t")
            .value_name("STRING")
            .help("Title of the LUT")
            .takes_value(true)
            .required(false)
            .validator(|value| {
                if value.contains("\"") {
                    return Err("Must not contain a double quote mark".to_string())
                }
                if value.len() > 242 {
                    return Err("Must not have a length greater than 242 bytes".to_string())
                }
                Ok(())
            })
        )
        .arg(Arg::with_name("size")
            .long("size")
            .short("s")
            .value_name("COUNT")
            .help("The size of each dimension of the 3D LUT")
            .takes_value(true)
            .required(false)
            .default_value("64")
            .validator(|value| {
                let size = value.parse::<usize>();
                if size.is_err() {
                    return Err("Must be an unsigned integer value".to_string())
                }
                let size_value = size.unwrap();
                if size_value < 2 || size_value > 256 {
                    return Err("Must be between 2 and 256".to_string())
                }
                Ok(())
            })
        )
        .arg(Arg::with_name("output")
            .index(1)
            .value_name("OUTPUT-FILE")
            .help("Output Cube LUT file; use - for STDOUT")
            .required(true)
        )
        .after_help(format!("This utility uses Oklab to generate a 3D LUT that will convert \
            BT.2020 SDR to BT.709 SDR.\n\n\
            Copyright © 2025 William Swartzendruber\n\
            Licensed under the Mozilla Public License 2.0\n\
            <{}>", env!("CARGO_PKG_REPOSITORY")).as_str())
        .get_matches();
    let title = matches.value_of("title");
    let size = matches.value_of("size").unwrap().parse::<usize>().unwrap();
    let output_value = matches.value_of("output").unwrap();
    let (mut stdout_write, mut file_write);
    let mut output = BufWriter::<&mut dyn Write>::new(
        if output_value == "-" {
            stdout_write = stdout();
            &mut stdout_write
        } else {
            file_write = File::create(output_value)
                .expect("Could not open output file for writing.");
            &mut file_write
        }
    );
    let mut rgb_in_pixels = Vec::<RgbPixel>::new();

    writeln!(output, "# Generated by GamutReduce {}", env!("CARGO_PKG_VERSION")).unwrap();
    if title.is_some() {
        writeln!(output, "TITLE \"{}\"", title.unwrap()).unwrap();
    }
    writeln!(output, "LUT_3D_SIZE {}", size).unwrap();

    for b in 0..size {
        for g in 0..size {
            for r in 0..size {

                let rgb_in_e = RgbPixel
                {
                    red: r as f64 / (size - 1) as f64,
                    green: g as f64 / (size - 1) as f64,
                    blue: b as f64 / (size - 1) as f64,
                };

                rgb_in_pixels.push(rgb_in_e);
            }
        }
    }

    let rgb_out_pixels =
        rgb_in_pixels
        .par_iter()
        .map(|rgb_in_e| {
            let rgb_in_o = rgb_in_e.with_each_channel(|x| sdr_e_to_o(x));
            let rgb_in_oklch = rgb_in_o.bt2020_to_xyz().to_oklab().to_oklch();
            let rgb_out_oklch = clamp_oklch(rgb_in_oklch);
            let rgb_out_o = rgb_out_oklch.to_oklab().to_xyz().to_rgb_bt709();
            rgb_out_o.clamp(0.0, 1.0).with_each_channel(|x| sdr_o_to_e(x))
        })
        .collect::<Vec<_>>();

    for rgb_out_e in rgb_out_pixels.iter() {
        writeln!(output, "{} {} {}",
            rgb_out_e.red as f32,
            rgb_out_e.green as f32,
            rgb_out_e.blue as f32,
        ).unwrap();
    }
}

fn clamp_oklch(oklch_pixel: OklchPixel) -> OklchPixel {

    let mut c = oklch_pixel.c;
    let max_diff = 1.000265;
    let min_diff = 0.0;

    loop {

        let oklch_test = OklchPixel {
            l: oklch_pixel.l,
            c,
            h: oklch_pixel.h,
        };
        let rgb_test = oklch_test.to_oklab().to_xyz().to_rgb_bt709();

        if rgb_test.red <= max_diff
            && rgb_test.green <= max_diff
            && rgb_test.blue <= max_diff
            && rgb_test.red >= min_diff
            && rgb_test.green >= min_diff
            && rgb_test.blue >= min_diff {
            return oklch_test;
        } else {
            c *= 0.999999;
        }
    }
}
